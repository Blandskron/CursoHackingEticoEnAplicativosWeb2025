# Comparar dos edades

mi_edad = int(input("Ingresa tu edad: "))
edad_amigo = int(input("Ingresa la edad de tu amigo/a: "))

if mi_edad > edad_amigo:
    print("Eres mayor que tu amigo/a.")
if mi_edad < edad_amigo:
    print("Eres menor que tu amigo/a.")
if mi_edad == edad_amigo:
    print("Tienen la misma edad.")
