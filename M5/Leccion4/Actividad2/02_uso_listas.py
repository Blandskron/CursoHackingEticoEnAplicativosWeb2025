# Este script muestra cómo crear y manipular una lista de nombres.

nombres = ["Ana", "Luis", "Camila", "Diego"]

# Imprimir toda la lista
print(nombres)

# Acceder a un elemento específico
print("Primer nombre:", nombres[0])

# Agregar un nuevo nombre a la lista
nombres.append("Esteban")
print("Lista actualizada:", nombres)

