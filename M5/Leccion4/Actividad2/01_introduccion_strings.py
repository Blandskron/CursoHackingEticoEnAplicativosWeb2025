# Este script introduce el concepto de cadenas (strings) y cómo combinarlas con variables.

nombre = "Ana"
saludo = "Hola, " + nombre + ". ¡Bienvenida a Python!"
print(saludo)

# También se puede usar una técnica moderna llamada f-string:
saludo_moderno = f"Hola, {nombre}. ¡Bienvenida a Python!"
print(saludo_moderno)
